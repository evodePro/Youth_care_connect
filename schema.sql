-- ==========================================
-- 1. ADVISORS TABLE
-- ==========================================
CREATE TABLE IF NOT EXISTS public.advisors (
  id UUID PRIMARY KEY REFERENCES auth.users(id),
  full_name TEXT NOT NULL,
  email TEXT NOT NULL,
  organization TEXT NOT NULL,
  role TEXT NOT NULL,
  phone TEXT,
  profile_picture_url TEXT,
  is_approved BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Enable RLS
ALTER TABLE public.advisors ENABLE ROW LEVEL SECURITY;

-- Allow public to read approved advisors (for the directory)
DROP POLICY IF EXISTS "Public can view approved advisors" ON public.advisors;
CREATE POLICY "Public can view approved advisors" ON public.advisors
  FOR SELECT USING (is_approved = TRUE);

-- Allow authenticated advisors to read/update/insert their own profile
-- This is critical: advisors need to read their own row even when NOT yet approved
DROP POLICY IF EXISTS "Advisors can manage own profile" ON public.advisors;
CREATE POLICY "Advisors can manage own profile" ON public.advisors
  FOR ALL 
  USING (auth.uid() = id)
  WITH CHECK (auth.uid() = id);

-- ==========================================
-- 2. CHATS TABLE
-- ==========================================
CREATE TABLE IF NOT EXISTS public.chats (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  youth_username TEXT NOT NULL,
  advisor_id UUID REFERENCES public.advisors(id),
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Enable RLS
ALTER TABLE public.chats ENABLE ROW LEVEL SECURITY;

-- Allow public (anonymous youth) to create a chat
DROP POLICY IF EXISTS "Public can start a chat" ON public.chats;
CREATE POLICY "Public can start a chat" ON public.chats
  FOR INSERT WITH CHECK (true);

-- Allow public to read chats (youth need to read their own chat by ID)
DROP POLICY IF EXISTS "Public can read chats" ON public.chats;
CREATE POLICY "Public can read chats" ON public.chats
  FOR SELECT USING (true);

-- Allow specific advisor to view their assigned chats
DROP POLICY IF EXISTS "Advisors can view assigned chats" ON public.chats;
CREATE POLICY "Advisors can view assigned chats" ON public.chats
  FOR SELECT USING (auth.uid() = advisor_id);

-- Allow advisors to update chats (e.g., mark as inactive/ended)
DROP POLICY IF EXISTS "Advisors can update own chats" ON public.chats;
CREATE POLICY "Advisors can update own chats" ON public.chats
  FOR UPDATE USING (auth.uid() = advisor_id);

-- ==========================================
-- 3. MESSAGES TABLE
-- ==========================================
CREATE TABLE IF NOT EXISTS public.messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chat_id UUID REFERENCES public.chats(id) ON DELETE CASCADE,
  sender_id TEXT NOT NULL, -- UUID or 'youth-xxxxxxxxx'
  role TEXT CHECK (role IN ('youth', 'advisor', 'system')),
  content TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Enable RLS
ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;

-- Allow anyone to read messages
DROP POLICY IF EXISTS "Anyone can read messages" ON public.messages;
CREATE POLICY "Anyone can read messages" ON public.messages
  FOR SELECT USING (true);

-- Allow anyone to insert messages (youth are anonymous, advisors are authenticated)
DROP POLICY IF EXISTS "Anyone can insert messages" ON public.messages;
CREATE POLICY "Anyone can insert messages" ON public.messages
  FOR INSERT WITH CHECK (true);

-- Allow anyone to delete messages
DROP POLICY IF EXISTS "Anyone can delete messages" ON public.messages;
CREATE POLICY "Anyone can delete messages" ON public.messages
  FOR DELETE USING (true);

-- Drop the old combined policy if it exists
DROP POLICY IF EXISTS "Public can access messages by chat_id" ON public.messages;

-- ==========================================
-- 3b. GRANT TABLE PERMISSIONS
-- ==========================================
-- These grants are REQUIRED for both anonymous youth and authenticated advisors
-- to be able to read/write to the tables. RLS alone is not enough without grants.
GRANT SELECT, INSERT, DELETE ON public.messages TO anon;
GRANT SELECT, INSERT, DELETE ON public.messages TO authenticated;
GRANT SELECT ON public.advisors TO anon;
GRANT SELECT, INSERT, UPDATE ON public.advisors TO authenticated;
GRANT SELECT, INSERT ON public.chats TO anon;
GRANT SELECT, INSERT, UPDATE ON public.chats TO authenticated;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO anon;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO authenticated;

-- ==========================================
-- 4. ENABLE REALTIME PUBLICATIONS
-- ==========================================
-- Enable Realtime for messages, chats, AND advisors (needed for pending.html auto-redirect)
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' 
    AND schemaname = 'public' 
    AND tablename = 'messages'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.messages;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' 
    AND schemaname = 'public' 
    AND tablename = 'chats'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.chats;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' 
    AND schemaname = 'public' 
    AND tablename = 'advisors'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.advisors;
  END IF;
END $$;

-- ==========================================
-- 5. REGISTRATION HELPER FUNCTION
-- ==========================================
-- This function runs with elevated privileges (SECURITY DEFINER)
-- to bypass RLS during registration, since the user may not be
-- fully authenticated yet (e.g., if email confirmation is enabled).
CREATE OR REPLACE FUNCTION public.create_advisor_profile(
  advisor_id UUID,
  advisor_full_name TEXT,
  advisor_email TEXT,
  advisor_organization TEXT,
  advisor_role TEXT,
  advisor_phone TEXT,
  advisor_profile_picture TEXT
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.advisors (id, full_name, email, organization, role, phone, profile_picture_url, is_approved)
  VALUES (advisor_id, advisor_full_name, advisor_email, advisor_organization, advisor_role, advisor_phone, advisor_profile_picture, FALSE);
END;
$$;

-- ==========================================
-- 6. STORAGE BUCKET FOR PROFILE PICTURES
-- ==========================================
-- The bucket "Profile" should already exist (created via Supabase Dashboard).
-- If not, create it manually: Dashboard → Storage → New Bucket → Name: "Profile" → Public: ON

-- Storage RLS Policies (REQUIRED — without these, uploads will fail)
DROP POLICY IF EXISTS "Public can view profile pictures" ON storage.objects;
CREATE POLICY "Public can view profile pictures" ON storage.objects
  FOR SELECT USING (bucket_id = 'Profile');

DROP POLICY IF EXISTS "Authenticated users can upload profile pictures" ON storage.objects;
CREATE POLICY "Authenticated users can upload profile pictures" ON storage.objects
  FOR INSERT WITH CHECK (bucket_id = 'Profile' AND auth.role() = 'authenticated');

-- Allow authenticated users to update/replace their own profile pictures
DROP POLICY IF EXISTS "Users can update own profile pictures" ON storage.objects;
CREATE POLICY "Users can update own profile pictures" ON storage.objects
  FOR UPDATE USING (bucket_id = 'Profile' AND auth.role() = 'authenticated');

-- Allow authenticated users to delete their own profile pictures
DROP POLICY IF EXISTS "Users can delete own profile pictures" ON storage.objects;
CREATE POLICY "Users can delete own profile pictures" ON storage.objects
  FOR DELETE USING (bucket_id = 'Profile' AND auth.role() = 'authenticated');
